package BitwiseOperators;

public class BitwiseLeftShift {
    public static void main(String[] args){
        int num = 5;
        System.out.println("Bitwise left shift of " + num + " by 1 is: " + (num << 1));

        int num1 = 3;
        System.out.println("Bitwise left shift of " + num1 + " by 2 is: " + (num1 << 2));

        int y = 4;
        System.out.println("Bitwise left shift of " + num1 + " by " + y + " is: " + (num1 << y));
    }
}
